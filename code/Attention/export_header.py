import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
W = dict(np.load(os.path.join(HERE, 'transformer_weights.npz')))
CFG = json.load(open(os.path.join(HERE, 'transformer_config.json')))

V, T, E = CFG['vocab_size'], CFG['block_size'], CFG['n_embd']
NH, HS, NL = CFG['n_head'], CFG['head_size'], CFG['n_layer']
SCALE, EPS = CFG['attn_scale'], CFG['layernorm_eps']

# ---------------------------------------------------------------- numpy reference
def layernorm(x, g, b):
    """Matches torch.nn.LayerNorm: biased variance, eps inside the sqrt."""
    mu = x.mean(-1, keepdims=True)
    var = ((x - mu) ** 2).mean(-1, keepdims=True)
    return (x - mu) / np.sqrt(var + EPS) * g + b


def forward(idx):
    """Full (non-cached) forward over a sequence. This is the spec the C port must match."""
    n = len(idx)
    x = W['tok_emb'][idx] + W['pos_emb'][:n]

    for L in range(NL):
        h = layernorm(x, W[f'l{L}_ln1_g'], W[f'l{L}_ln1_b'])
        q, k, v = h @ W[f'l{L}_q'], h @ W[f'l{L}_k'], h @ W[f'l{L}_v']

        heads = []
        for hh in range(NH):
            s = slice(hh * HS, (hh + 1) * HS)
            att = (q[:, s] @ k[:, s].T) * SCALE
            att = np.where(np.tril(np.ones((n, n))) == 0, -np.inf, att)
            att = att - att.max(-1, keepdims=True)
            att = np.exp(att)
            att /= att.sum(-1, keepdims=True)
            heads.append(att @ v[:, s])
        x = x + np.concatenate(heads, -1) @ W[f'l{L}_o'] + W[f'l{L}_o_b']

        h = layernorm(x, W[f'l{L}_ln2_g'], W[f'l{L}_ln2_b'])
        f = np.maximum(h @ W[f'l{L}_fc'] + W[f'l{L}_fc_b'], 0.0)
        x = x + f @ W[f'l{L}_pr'] + W[f'l{L}_pr_b']

    x = layernorm(x, W['lnf_g'], W['lnf_b'])
    return x @ W['head'] + W['head_b']


# Fixed reference sequence: start token then "kev" -> exercises embedding, both
# layers, causal masking at 4 positions, and the output head.
REF_IN = [0, 11, 5, 22]
REF_OUT = forward(np.array(REF_IN)).astype(np.float32)

# ---------------------------------------------------------------- header emission
def c_array(name, a):
    a = np.asarray(a, dtype=np.float32)
    fmt = lambda v: f'{v:.8g}f'
    if a.ndim == 1:
        body = ', '.join(fmt(v) for v in a)
        return f'const float {name}[{a.shape[0]}] = {{{body}}};\n'
    rows = ',\n  '.join('{' + ', '.join(fmt(v) for v in r) + '}' for r in a)
    return f'const float {name}[{a.shape[0]}][{a.shape[1]}] = {{\n  {rows}\n}};\n'


order = ['tok_emb', 'pos_emb']
for L in range(NL):
    order += [f'l{L}_ln1_g', f'l{L}_ln1_b', f'l{L}_q', f'l{L}_k', f'l{L}_v',
              f'l{L}_o', f'l{L}_o_b', f'l{L}_ln2_g', f'l{L}_ln2_b',
              f'l{L}_fc', f'l{L}_fc_b', f'l{L}_pr', f'l{L}_pr_b']
order += ['lnf_g', 'lnf_b', 'head', 'head_b']

total = sum(W[k].size for k in order)
lines = [
    '// Generated by export_header.py -- do not edit by hand.\n',
    f'// {CFG["n_params"]} params, {total} exported floats, {total * 4 / 1024:.1f} KB\n',
    f'// test loss {CFG["losses"]["test"]:.4f}  val {CFG["losses"]["val"]:.4f}'
    f'  train {CFG["losses"]["train"]:.4f}\n',
    '#pragma once\n\n',
    f'#define TFM_VOCAB   {V}\n#define TFM_BLOCK   {T}\n#define TFM_EMBD    {E}\n',
    f'#define TFM_HEADS   {NH}\n#define TFM_HEADSZ  {HS}\n#define TFM_LAYERS  {NL}\n',
    f'#define TFM_SCALE   {SCALE:.9g}f\n#define TFM_LN_EPS  {EPS:.3g}f\n\n',
]
for k in order:
    lines.append(c_array('TFM_' + k, W[k]))

lines.append(f'\n// Golden reference: forward([{", ".join(map(str, REF_IN))}]).\n')
lines.append('// C port must reproduce these to ~1e-4 before any timing is trusted.\n')
lines.append(f'const int TFM_REF_IN[{len(REF_IN)}] = {{{", ".join(map(str, REF_IN))}}};\n')
lines.append(c_array('TFM_REF_LOGITS', REF_OUT))

out_path = os.path.join(HERE, 'transformer_weights.h')
with open(out_path, 'w') as f:
    f.writelines(lines)

print(f'wrote {out_path}')
print(f'  {total} floats = {total * 4 / 1024:.1f} KB flash (const) + same again if copied to RAM')
print(f'  KV cache at block={T}: {NL * T * E * 2 * 4 / 1024:.1f} KB')
print(f'  reference logits[last position], first 5: {REF_OUT[-1][:5]}')
print(f'  argmax at each position: {REF_OUT.argmax(-1).tolist()}')